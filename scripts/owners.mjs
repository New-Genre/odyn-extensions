#!/usr/bin/env node
/**
 * Writes `.github/CODEOWNERS` from each extension's `odyn.owners`, so GitHub
 * asks an extension's owners to review any change to it. Odyn's maintainers
 * are listed on every line too: they can always review, and have the final say.
 *
 *   node scripts/owners.mjs           rewrites the file
 *   node scripts/owners.mjs --check   fails if the file is out of date
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { extensionFolders, readPackage } from './build.mjs'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CODEOWNERS = join(repoRoot, '.github', 'CODEOWNERS')
const MAINTAINERS = ['@jacksmethurst']

export function codeowners() {
  const lines = [
    '# Generated by scripts/owners.mjs from each extension\'s `odyn.owners`. Do not edit by hand.',
    '# Everything merged here is downloaded by Odyn users, so every change needs a review.',
    `* ${MAINTAINERS.join(' ')}`,
  ]
  for (const folder of extensionFolders()) {
    const owners = readPackage(folder).odyn?.owners
    if (!Array.isArray(owners) || owners.length === 0) continue
    const handles = [...new Set([...owners.map((owner) => `@${owner}`), ...MAINTAINERS])]
    lines.push(`/extensions/${folder}/ ${handles.join(' ')}`)
  }
  return `${lines.join('\n')}\n`
}

const next = codeowners()
const current = existsSync(CODEOWNERS) ? readFileSync(CODEOWNERS, 'utf8') : ''
if (process.argv.includes('--check')) {
  if (current !== next) {
    console.error('[owners] .github/CODEOWNERS is out of date. Run `node scripts/owners.mjs`.')
    process.exit(1)
  }
} else if (current !== next) {
  writeFileSync(CODEOWNERS, next)
  console.log('[owners] updated .github/CODEOWNERS')
}
